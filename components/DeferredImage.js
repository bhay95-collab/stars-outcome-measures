/**
 * Landing-page photo that defers its own download until it is near the viewport.
 *
 * The deferral is done by the browser (`loading="lazy"`), not by JavaScript, so
 * the URL is present in the server-rendered HTML. That matters on slow
 * connections: the preload scanner can queue the image while the JS bundle is
 * still downloading, and the image still appears if the bundle never arrives.
 *
 * `sources` carries the WebP variants and `srcSet` the JPEG ones, so the
 * browser picks a file sized for the slot it is rendered in rather than
 * downloading the full-size original. Variants are generated by
 * `scripts/build-landing-media.js`; `sizes` values are measured from the real
 * layout, so re-measure if the layout changes.
 */
export default function DeferredImage({
  alt,
  className,
  decoding = 'async',
  fetchPriority,
  height,
  loading = 'lazy',
  sizes,
  sources = [],
  src,
  srcSet,
  width,
}) {
  const image = (
    <img
      alt={alt}
      className={className}
      decoding={decoding}
      fetchPriority={fetchPriority}
      height={height}
      loading={loading}
      sizes={sizes}
      src={src}
      srcSet={srcSet}
      width={width}
    />
  )

  if (sources.length === 0) return image

  return (
    <picture>
      {sources.map(source => (
        <source
          key={`${source.type}-${source.srcSet}`}
          media={source.media}
          sizes={source.sizes || sizes}
          srcSet={source.srcSet}
          type={source.type}
        />
      ))}
      {image}
    </picture>
  )
}
